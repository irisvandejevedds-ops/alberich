# the dict literal lines above end with trailing commas that make tuples; normalise
ICONS = {}
for _k, _v in I.items():
    _s = _v[0] if isinstance(_v, tuple) else _v
    ICONS[_k] = [r for r in _s.strip("\n").split("\n")]

PICKER = ["takeout", "drinks", "coffee", "cake", "toy", "gift", "shopping", "cart", "basket", "ticket", "film", "game", "book", "car", "plane", "heart", "pill", "star"]
EMOJI = {"🥡": "takeout", "🍻": "drinks", "🍺": "drinks", "🧸": "toy", "🛍": "shopping", "🎟": "ticket", "🛒": "cart", "🧺": "basket",
         "☕": "coffee", "🎁": "gift", "🎮": "game", "📚": "book", "🚗": "car", "✈": "plane", "❤": "heart", "🎂": "cake", "🎬": "film"}


def normalise(value):
    v = (value or "").strip()
    if v in ICONS:
        return v
    for e, k in EMOJI.items():
        if v.startswith(e):
            return k
    return "star"


@lru_cache(maxsize=None)
def _paths(name):
    rows = ICONS[name]
    by = {}
    for y, row in enumerate(rows):
        row = row.ljust(16, ".")[:16]
        x = 0
        while x < 16:
            c = row[x]
            if c == ".":
                x += 1
                continue
            e = x
            while e < 16 and row[e] == c:
                e += 1
            by.setdefault(c, []).append(f"M{x} {y}h{e - x}v1h-{e - x}z")
            x = e
    return "".join(f'<path fill="{PAL[c]}" d="{"".join(p)}"/>' for c, p in by.items())


def svg(name, size=24, cls=""):
    name = normalise(name)
    return (f'<svg class="px {cls}" width="{size}" height="{size}" viewBox="0 0 16 16" shape-rendering="crispEdges" '
            f'xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">{_paths(name)}</svg>')


def migrate_db(db):
    for a in db.q("SELECT id, icon FROM activities"):
        n = normalise(a["icon"])
        if n != a["icon"]:
            db.ex("UPDATE activities SET icon=? WHERE id=?", (n, a["id"]))
