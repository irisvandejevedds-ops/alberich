"""Generates web/assets.js (Alberich's five moods, the pouch icons) from the Python that already draws them, so the art is defined once.
    /opt/finapp/venv/bin/python web/build_assets.py"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app"))
from finapp import pxicons, sprites  # noqa: E402

moods = {}
for m in sprites.MOODS:
    cells = sprites.grid(m)
    rows = ["".join(cells.get((x, y), ".") for x in range(sprites.W)) for y in range(sprites.H)]
    moods[m] = {"rows": rows, "palette": sprites.PALETTES[m]}
icons = {k: [r.ljust(16, ".")[:16] for r in v][:16] for k, v in pxicons.ICONS.items()}
out = {"w": sprites.W, "h": sprites.H, "moods": moods, "icons": icons, "iconPalette": pxicons.PAL, "picker": pxicons.PICKER}
(ROOT / "web/assets.js").write_text("/* generated by build_assets.py: do not edit */\nwindow.AlberichAssets = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("assets.js", len((ROOT / "web/assets.js").read_text()), "bytes;", len(moods), "moods;", len(icons), "icons")
